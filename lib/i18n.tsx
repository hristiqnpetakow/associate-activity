const LanguageContext = createContext<{
  language: Language;
  setLanguage: (language: Language) => void;
  toggleLanguage: () => void;
  t: (key: string, vars?: Record<string, string | number>) => string;
}>({
  language: 'bg',
  setLanguage: () => undefined,
  toggleLanguage: () => undefined,
  t: (key) => key,
});

export function LanguageProvider({ children }: { children: React.ReactNode }) {
  const [language, setLanguageState] = useState<Language>('bg');

  useEffect(() => {
    const saved = localStorage.getItem('activity-language');
    if (saved === 'en' || saved === 'bg') setLanguageState(saved);
  }, []);

  useEffect(() => {
    localStorage.setItem('activity-language', language);
    document.documentElement.lang = language;
  }, [language]);

  const value = useMemo(() => {
    const dict = language === 'en' ? en : bg;
    return {
      language,
      setLanguage: (next: Language) => setLanguageState(next),
      toggleLanguage: () => setLanguageState((current) => current === 'bg' ? 'en' : 'bg'),
      t: (key: string, vars?: Record<string, string | number>) => {
        let text = dict[key] ?? bg[key] ?? key;
        Object.entries(vars ?? {}).forEach(([name, val]) => {
          text = text.replaceAll(`{${name}}`, String(val));
        });
        return text;
      },
    };
  }, [language]);

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useLanguage() {
  return useContext(LanguageContext);
}
